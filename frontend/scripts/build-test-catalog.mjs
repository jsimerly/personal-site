/**
 * Generate TESTING.md: every frontend test, unit and E2E, as a plain-English
 * claim grouped by file and describe block. The describe/it names ARE the
 * catalog, so write them as full sentences. Lists tests without running them:
 *
 *   npm run test:catalog
 */
import { execSync } from 'node:child_process'
import { readFileSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const relative = (file) => path.relative(ROOT, path.resolve(ROOT, file)).replaceAll('\\', '/')

function unitTests() {
  const out = path.join(ROOT, '.vitest-list.json')
  execSync(`npx vitest list --json=${JSON.stringify(out)}`, { cwd: ROOT, stdio: 'ignore' })
  const listed = JSON.parse(readFileSync(out, 'utf8'))
  rmSync(out)
  return listed.map(({ name, file }) => {
    const parts = name.split(' > ')
    return { file: relative(file), group: parts.slice(0, -1).join(' › '), title: parts.at(-1) }
  })
}

function e2eTests() {
  const report = JSON.parse(execSync('npx playwright test --list --reporter=json', { cwd: ROOT, encoding: 'utf8' }))
  const tests = new Map()
  const walk = (suite, file, groups) => {
    for (const spec of suite.specs ?? []) {
      const group = groups.join(' › ')
      // One entry per test, not per browser project.
      tests.set(`${file}\0${group}\0${spec.title}`, { file, group, title: spec.title })
    }
    for (const child of suite.suites ?? []) walk(child, file, [...groups, child.title])
  }
  for (const fileSuite of report.suites) walk(fileSuite, `e2e/${fileSuite.file}`, [])
  return [...tests.values()]
}

function section(title, tests) {
  const lines = ['', `## ${title}`]
  const byFile = Map.groupBy(tests, (test) => test.file)
  for (const file of [...byFile.keys()].sort()) {
    const fileTests = byFile.get(file)
    lines.push('', `### ${file} (${fileTests.length} tests)`, '')
    let lastGroup = null
    for (const { group, title } of fileTests) {
      if (group && group !== lastGroup) lines.push(`- **${group}**`)
      lastGroup = group
      lines.push(`${group ? '  ' : ''}- ${title}`)
    }
  }
  return lines
}

const unit = unitTests()
const e2e = e2eTests()
const lines = [
  '# Frontend test catalog',
  '',
  "Generated by `npm run test:catalog`. Regenerate after adding tests; don't edit",
  'by hand. Each line is the behavior a test pins, taken from its describe/it names',
  '(write them as sentences).',
  '',
  'Run: `npm test` (unit), `npm run e2e` (end to end). Check the exit code, never',
  'pipe it to tail.',
  ...section('Unit and component tests (Vitest)', unit),
  ...section('End-to-end tests (Playwright, each on a phone and a laptop)', e2e),
  '',
  '---',
  '',
  `${unit.length} unit and ${e2e.length} end-to-end tests cataloged.`,
  '',
]

writeFileSync(path.join(ROOT, 'TESTING.md'), lines.join('\n'))
console.log(`wrote TESTING.md (${unit.length} unit, ${e2e.length} e2e)`)
